$generated=@()
$reused=@()
foreach($g in $core){
  $dst=Join-Path $ModelsDir "$($g.N).glb"
  if(Test-Path -LiteralPath $dst){ Log "SKIP existing $($g.N)"; $reused += $g.N; continue }
  $bal=Get-Balance
  if($bal -ge 0 -and $bal -lt 25){ throw "Meshy balance too low before $($g.N): $bal" }
  Log "GENERATE missing core slot $($g.N)"
  $pc=Invoke-Meshy 'POST' '/openapi/v2/text-to-3d' @{ mode='preview'; model_type='standard'; ai_model='latest'; prompt=$g.Q; should_remesh=$true; topology='quad'; target_polycount=$g.P; target_formats=@('glb','fbx'); auto_size=$false }
  $preview=Wait-Task '/openapi/v2/text-to-3d' $pc.result 2400
  $rc=Invoke-Meshy 'POST' '/openapi/v2/text-to-3d' @{ mode='refine'; preview_task_id=$preview.id; enable_pbr=$true; texture_resolution='4k'; remove_lighting=$true; target_formats=@('glb','fbx') }
  $refined=Wait-Task '/openapi/v2/text-to-3d' $rc.result 2400
  Download-Model $refined $g.N
  $generated += $g.N
}

$required=@('Body_Rigged','Helmet','ChestArmor','Shoulders','Gloves','Belt','Legs','Boots','Cloak','Sword','Shield','ClassRelic')
$missing=@()
foreach($n in $required){ if(-not (Test-Path -LiteralPath (Join-Path $ModelsDir "$n.glb"))){ $missing += $n } }
$summary=[ordered]@{ source_run=$SourceRunRoot; output_root=$OutputRoot; generated=$generated; reused=$reused; missing=$missing; jewellery_excluded=@('Ring_L','Ring_R','Necklace','Bracelet'); rig_required=$true; balance_end=(Get-Balance) }
$summary|ConvertTo-Json -Depth 6|Set-Content -LiteralPath (Join-Path $ReportsDir 'resume_summary.json') -Encoding UTF8
if($missing.Count -gt 0){ throw "Missing required core assets after resume: $($missing -join ', ')" }
Log 'CORE_ONLY_RESUME_DONE'
